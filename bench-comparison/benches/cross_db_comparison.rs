fn fmt_dur(d: Duration) -> String {
    let ns = d.as_nanos();
    if ns < 1_000 {
        format!("{} ns", ns)
    } else if ns < 1_000_000 {
        format!("{:.2} µs", ns as f64 / 1_000.0)
    } else if ns < 1_000_000_000 {
        format!("{:.2} ms", ns as f64 / 1_000_000.0)
    } else {
        format!("{:.2} s", ns as f64 / 1_000_000_000.0)
    }
}

fn median(mut durs: Vec<Duration>) -> Duration {
    if durs.is_empty() {
        return Duration::default();
    }
    durs.sort();
    durs[durs.len() / 2]
}

fn print_header() {
    let mut header = String::from("| ORM |");
    let mut sep = String::from("|-----|");
    for i in 0..TRIALS {
        header.push_str(&format!(" Trial {} |", i + 1));
        sep.push_str("------|");
    }
    header.push_str(" Median |");
    sep.push_str("--------|");
    println!("{}", header);
    println!("{}", sep);
}

fn print_row(name: &str, times: &[Duration]) {
    let med = median(times.to_vec());
    let trials_str: Vec<String> = times.iter().map(|t| fmt_dur(*t)).collect();
    println!("| {} | {} | {} |", name, trials_str.join(" | "), fmt_dur(med));
}

/// 屏蔽密码后输出 URL
fn mask_url(url: &str) -> String {
    if let Some(at) = url.find('@') {
        if let Some(colon) = url.find(':') {
            if colon < at {
                let scheme_end = url.find("://").map(|i| i + 3).unwrap_or(0);
                if scheme_end <= colon {
                    let mut masked = String::new();
                    masked.push_str(&url[..colon + 1]);
                    masked.push_str("***");
                    masked.push_str(&url[at..]);
                    return masked;
                }
            }
        }
    }
    url.to_string()
}

/// 批量插入 setup 数据（多行 VALUES 减少网络 RTT）
async fn batch_insert_sqlite(sqlx_pool: &sqlx::SqlitePool, n: usize, batch_size: usize) -> Result<(), BoxError> {
    let mut inserted = 0;
    while inserted < n {
        let batch_end = (inserted + batch_size).min(n);
        let mut sql = String::from("INSERT INTO bench_users (name, email, age) VALUES ");
        for i in inserted..batch_end {
            if i > inserted {
                sql.push(',');
            }
            sql.push_str(&format!("('user_{}', 'user_{}@test.com', {})", i, i, i % 100));
        }
        let sql_ref = sql;
        sqlx::query(sqlx::AssertSqlSafe(&*sql_ref)).execute(sqlx_pool).await?;
        inserted = batch_end;
    }
    Ok(())
}

