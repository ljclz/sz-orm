/// Oracle 批量插入（Oracle 不支持多行 VALUES，使用 INSERT ALL）
fn batch_insert_oracle_stmt(n: usize, batch_size: usize) -> String {
    let mut sql = String::from("INSERT ALL ");
    let mut inserted = 0;
    while inserted < n {
        let batch_end = (inserted + batch_size).min(n);
        for i in inserted..batch_end {
            sql.push_str(&format!(
                "INTO bench_users (name, email, age) VALUES ('user_{}', 'user_{}@test.com', {}) ",
                i, i, i % 100
            ));
        }
        inserted = batch_end;
    }
    sql.push_str("SELECT 1 FROM DUAL");
    sql
}

