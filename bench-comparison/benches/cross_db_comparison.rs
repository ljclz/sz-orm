//! 跨数据库 + 跨 ORM 横向对比基准（harness = false，自定义 main）
//!
//! # 矩阵
//!
//! | 数据库     | SZ-ORM | sqlx | diesel | sea-orm | raw oracle | 触发方式                  |
//! |-----------|:------:|:----:|:------:|:-------:|:----------:|--------------------------|
//! | SQLite    |   ✓    |  ✓   |   ✓    |   ✓     |     -      | 始终运行（in-memory）     |
//! | MySQL     |   ✓    |  ✓   |   ✓    |   ✓     |     -      | `DATABASE_URL_MYSQL`      |
//! | PostgreSQL|   ✓    |  ✓   |   ✓    |   ✓     |     -      | `DATABASE_URL_POSTGRES`   |
//! | Oracle    |   ✓    |  -   |   -    |   -     |     ✓      | `DATABASE_URL_ORACLE`     |
//!
//! # 场景（每 DB × 每 ORM）
//!
//! - INSERT 1K rows    （SQLite/远程均 1K；文件 DB + WAL 每行 fsync，1K 足够观察 ORM 开销）
//! - SELECT BY ID 100× （所有 DB 一致）
//! - SELECT ALL 1K     （所有 DB 一致）
//! - UPDATE 100 rows   （所有 DB 一致）
//! - DELETE 1K rows    （所有 DB 一致）
//!
//! # SZ-ORM 优化路径
//!
//! - INSERT/UPDATE/DELETE 使用 `execute_with_params`（真实 prepared statement）
//! - SELECT BY ID 使用 `query_with_params`
//! - SELECT ALL 使用 `query_values`（位置式映射，绕过 HashMap 开销）
//!
//! # 用法
//!
//! ```bash
//! # 仅 SQLite（in-memory，始终运行）
//! cargo bench --bench cross_db_comparison
//!
//! # 全数据库（需提供连接串）
//! $env:DATABASE_URL_MYSQL="mysql://user:pass@host:3306/db"
//! $env:DATABASE_URL_POSTGRES="postgres://user:pass@host:5432/db"
//! $env:DATABASE_URL_ORACLE="user/pass@//host:1521/service"
//! cargo bench --bench cross_db_comparison
//! ```

