#[cfg(feature = "oracle")]
async fn bench_oracle_select_all(
    sz_pool: &SzPool,
    username: &str,
    password: &str,
    connect_string: &str,
    n: usize,
) -> Result<(), BoxError> {
    println!("### SELECT ALL (Oracle, {} rows)\n", n);
    print_header();

    // 数据已预插入；若 count != n 则补 setup
    {
        let mut conn = sz_pool.acquire().await?;
        let rows = conn.query("SELECT COUNT(*) FROM bench_users").await?;
        let count = rows
            .first()
            .and_then(|r| r.values().next())
            .and_then(|v| v.as_i64())
            .unwrap_or(0);
        if count as usize != n {
            conn.execute(ORACLE_TRUNCATE).await?;
            for chunk_start in (0..n).step_by(100) {
                let chunk_end = (chunk_start + 100).min(n);
                let mut sql = String::from("INSERT ALL ");
                for i in chunk_start..chunk_end {
                    sql.push_str(&format!(
                        "INTO bench_users (name, email, age) VALUES ('user_{}', 'user_{}@test.com', {}) ",
                        i, i, i % 100
                    ));
                }
                sql.push_str("SELECT 1 FROM DUAL");
                conn.execute(&sql).await?;
            }
        }
    }

    // SZ-ORM (query_values 位置式映射)
    let mut sz_times = Vec::new();
    for _ in 0..TRIALS {
        let start = Instant::now();
        let mut conn = sz_pool.acquire().await?;
        let (cols, rows) = conn
            .query_values("SELECT id, name, email, age FROM bench_users")
            .await?;
        sz_times.push(start.elapsed());
        let _ = (cols.len(), rows.len());
    }
    print_row("sz-orm (values)", &sz_times);

    // SZ-ORM (query_with_params HashMap 映射)
    let mut sz_hash_times = Vec::new();
    for _ in 0..TRIALS {
        let start = Instant::now();
        let mut conn = sz_pool.acquire().await?;
        let rows = conn
            .query_with_params("SELECT id, name, email, age FROM bench_users", &[])
            .await?;
        sz_hash_times.push(start.elapsed());
        let _ = rows.len();
    }
    print_row("sz-orm (hashmap)", &sz_hash_times);

    // raw oracle
    let mut raw_times = Vec::new();
    for _ in 0..TRIALS {
        let conn = oracle::Connection::connect(username, password, connect_string)?;
        let start = Instant::now();
        let stmt = conn.statement("SELECT id, name, email, age FROM bench_users").build()?;
        let rows = stmt.query(&[])?;
        let count = rows.count();
        raw_times.push(start.elapsed());
        let _ = count;
        conn.close().ok();
    }
    print_row("raw oracle", &raw_times);

    println!();
    Ok(())
}

