async fn ensure_mysql_database(url: &str) -> Result<(), BoxError> {
    if let Some(db_start) = url.rfind('/') {
        let db_name = &url[db_start + 1..];
        if !db_name.is_empty() {
            let base_url = format!("{}/mysql", &url[..db_start]);
            let pool = sqlx::mysql::MySqlPoolOptions::new()
                .max_connections(1)
                .connect(&base_url)
                .await?;
            let create_sql = format!("CREATE DATABASE IF NOT EXISTS `{}`", db_name);
            sqlx::query(sqlx::AssertSqlSafe(&*create_sql)).execute(&pool).await?;
            pool.close().await;
            println!("[setup] MySQL database '{}' ensured", db_name);
        }
    }
    Ok(())
}

async fn run_mysql_bench(url: &str) -> Result<(), BoxError> {
    println!("## MySQL Benchmark\n");
    println!("Connection: `{}`", mask_url(url));
    println!("Rows per scenario: {} (queries: {})\n", REMOTE_ROWS, REMOTE_QUERIES);

    ensure_mysql_database(url).await?;

    // SZ-ORM MySQL
    let sz_handle = Arc::new(MySqlPoolHandle::connect(url).await?);
    let sz_factory = Arc::new(SqlxMySqlConnectionFactory::new(sz_handle.clone()));
    let sz_config = PoolConfigBuilder::new().max_size(10).build()?;
    let sz_pool = SzPool::new(sz_config, sz_factory)?;

    // sqlx MySQL
    let sqlx_pool = sqlx::mysql::MySqlPoolOptions::new()
        .max_connections(10)
        .connect(url)
        .await?;

    // SeaORM MySQL
    let mut opt = ConnectOptions::new(url.to_string());
    opt.max_connections(10);
    let sea_db = Database::connect(opt).await?;

    // Diesel MySQL
    #[cfg(feature = "diesel-mysql")]
    let mut diesel_conn = diesel::mysql::MysqlConnection::establish(url).map_err(|e| -> BoxError {
        format!("diesel mysql connect failed: {}", e).into()
    })?;
    #[cfg(not(feature = "diesel-mysql"))]
    let mut diesel_conn: DieselMysqlConn = ();

    // 创建表
    sqlx::query(MYSQL_CREATE).execute(&sqlx_pool).await?;

    let n = REMOTE_ROWS;
    let queries = REMOTE_QUERIES;

    bench_mysql_insert(&sz_pool, &sqlx_pool, &sea_db, &mut diesel_conn, n).await?;
    bench_mysql_select_by_id(&sz_pool, &sqlx_pool, &sea_db, &mut diesel_conn, n, queries).await?;
    bench_mysql_select_all(&sz_pool, &sqlx_pool, &sea_db, &mut diesel_conn, n).await?;
    bench_mysql_update(&sz_pool, &sqlx_pool, &sea_db, &mut diesel_conn, n, queries).await?;
    bench_mysql_delete(&sz_pool, &sqlx_pool, &sea_db, &mut diesel_conn, n).await?;

    // 清理
    sqlx::query("DROP TABLE IF EXISTS bench_users").execute(&sqlx_pool).await?;
    sz_pool.close_all().await;
    sqlx_pool.close().await;
    let _ = sea_db.close().await;

    Ok(())
}

