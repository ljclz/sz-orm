// === generate_from_db ===

#[test]
fn test_generate_from_db_basic() {
    let gen = EntityGenerator::new();
    let tables = vec![DbTableSchema {
        name: "users".to_string(),
        columns: vec![
            DbColumnSchema {
                name: "id".to_string(),
                db_type: "bigint".to_string(),
                is_primary_key: true,
                is_nullable: false,
            },
            DbColumnSchema {
                name: "name".to_string(),
                db_type: "varchar".to_string(),
                is_primary_key: false,
                is_nullable: false,
            },
            DbColumnSchema {
                name: "email".to_string(),
                db_type: "varchar".to_string(),
                is_primary_key: false,
                is_nullable: true,
            },
        ],
        foreign_keys: vec![],
    }];
    let code = gen.generate_from_db(&tables);
    assert!(code.contains("pub struct UsersModel"));
    assert!(code.contains("pub id: i64"));
    assert!(code.contains("pub name: String"));
    assert!(code.contains("pub email: Option<String>"));
}

#[test]
fn test_generate_from_db_with_foreign_keys() {
    let gen = EntityGenerator::new();
    let tables = vec![DbTableSchema {
        name: "orders".to_string(),
        columns: vec![DbColumnSchema {
            name: "id".to_string(),
            db_type: "bigint".to_string(),
            is_primary_key: true,
            is_nullable: false,
        }],
        foreign_keys: vec![DbForeignKey {
            local_column: "user_id".to_string(),
            target_table: "users".to_string(),
            target_column: "id".to_string(),
        }],
    }];
    let code = gen.generate_from_db(&tables);
    assert!(code.contains("pub struct OrdersModel"));
    // generate() 按 RelationType::BelongsTo 生成关系方法 `pub fn usersmodel`
    // （枚举名本身不进入生成代码，见 entity_generator.rs:145）
    assert!(code.contains("pub fn usersmodel"));
    assert!(code.contains("UsersModel"));
}

