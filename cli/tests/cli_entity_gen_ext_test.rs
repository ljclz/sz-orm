#[test]
fn test_generate_idempotent_sorts_fields() {
    let gen = EntityGenerator::new();
    let entity = EntityDefinition::new("User", "users")
        .with_field(EntityField::new("zebra", "String", "varchar"))
        .with_field(EntityField::new("apple", "String", "varchar"))
        .with_field(EntityField::new("mango", "String", "varchar"));
    let code = gen.generate_idempotent(&entity);
    let apple_pos = code.find("pub apple").unwrap();
    let mango_pos = code.find("pub mango").unwrap();
    let zebra_pos = code.find("pub zebra").unwrap();
    assert!(apple_pos < mango_pos);
    assert!(mango_pos < zebra_pos);
}

#[test]
fn test_generate_idempotent_is_deterministic() {
    let gen = EntityGenerator::new();
    let entity = EntityDefinition::new("User", "users")
        .with_field(EntityField::new("id", "i64", "bigint").primary_key())
        .with_field(EntityField::new("name", "String", "varchar").nullable());
    let code1 = gen.generate_idempotent(&entity);
    let code2 = gen.generate_idempotent(&entity);
    assert_eq!(code1, code2);
}

#[test]
fn test_generate_idempotent_sorts_relations() {
    let gen = EntityGenerator::new();
    let entity = EntityDefinition::new("User", "users")
        .with_field(EntityField::new("id", "i64", "bigint").primary_key())
        .with_relation(EntityRelation {
            relation_type: RelationType::HasMany,
            target_entity: "ZOrder".to_string(),
            local_field: "id".to_string(),
            target_field: "user_id".to_string(),
        })
        .with_relation(EntityRelation {
            relation_type: RelationType::HasOne,
            target_entity: "AProfile".to_string(),
            local_field: "id".to_string(),
            target_field: "user_id".to_string(),
        });
    let code = gen.generate_idempotent(&entity);
    let a_pos = code.find("aprofile").unwrap();
    let z_pos = code.find("zorder").unwrap();
    assert!(a_pos < z_pos);
}

