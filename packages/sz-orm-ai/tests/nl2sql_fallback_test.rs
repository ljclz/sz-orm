//! Nl2SqlFallbackChain 端到端测试（v10.9.0 T2.1）
//!
//! 验证多模型 fallback 包装器的行为副作用：
//! - 主引擎成功时直接返回
//! - 主引擎失败时自动降级到备用引擎
//! - 所有引擎失败时返回最后一个错误
//! - LLM 安全审计在每一级 fallback 都调用（安全不降级）
//! - fallback 日志记录每级失败原因
//! - 空引擎列表和超过 5 个引擎返回 ConfigError

#![cfg(feature = "ai-security-audit")]

use async_trait::async_trait;
use sz_orm_ai::nl2sql::{
    Nl2SqlError, Nl2SqlEngine, Nl2SqlFallbackChain, SchemaContext, SqlQuery,
};
use sz_orm_ai::llm_security_audit::LlmSecurityAuditor;

/// 可控的模拟引擎：按配置决定成功或失败
struct MockEngine {
    name: String,
    should_succeed: bool,
}

impl MockEngine {
    fn new(name: &str, should_succeed: bool) -> Self {
        Self {
            name: name.to_string(),
            should_succeed,
        }
    }
}

#[async_trait]
impl Nl2SqlEngine for MockEngine {
    async fn generate(
        &self,
        nl_query: &str,
        _schema: &SchemaContext,
    ) -> Result<SqlQuery, Nl2SqlError> {
        if self.should_succeed {
            Ok(SqlQuery {
                sql: format!("SELECT 1 -- {} for: {}", self.name, nl_query),
                explanation: format!("generated by {}", self.name),
                confidence: 0.9,
                dialect: None,
                cache_hit: false,
            })
        } else {
            Err(Nl2SqlError::GenerationError(format!(
                "{} intentionally failed",
                self.name
            )))
        }
    }

    async fn validate(&self, _query: &SqlQuery) -> Result<bool, Nl2SqlError> {
        Ok(self.should_succeed)
    }
}

fn empty_schema() -> SchemaContext {
    SchemaContext::default()
}

#[tokio::test]
async fn test_fallback_chain_primary_success() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("primary", true)),
        Box::new(MockEngine::new("backup", true)),
    ])
    .unwrap();

    let result = chain.generate("show users", &empty_schema()).await.unwrap();
    assert!(result.sql.contains("primary"), "应使用主引擎");
    assert!(chain.fallback_log().is_empty(), "无 fallback 时日志为空");
}

#[tokio::test]
async fn test_fallback_chain_primary_fail_fallback_success() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("primary", false)),
        Box::new(MockEngine::new("backup", true)),
    ])
    .unwrap();

    let result = chain.generate("show users", &empty_schema()).await.unwrap();
    assert!(result.sql.contains("backup"), "应降级到备用引擎");

    let log = chain.fallback_log();
    assert_eq!(log.len(), 1, "应记录 1 次 fallback");
    assert!(log[0].contains("primary"), "日志应包含主引擎失败原因");
}

#[tokio::test]
async fn test_fallback_chain_all_fail() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("primary", false)),
        Box::new(MockEngine::new("backup", false)),
    ])
    .unwrap();

    let err = chain.generate("show users", &empty_schema())
        .await
        .unwrap_err();
    assert!(
        matches!(err, Nl2SqlError::GenerationError(_)),
        "应返回 GenerationError"
    );

    let log = chain.fallback_log();
    assert_eq!(log.len(), 2, "应记录 2 次 fallback");
}

#[tokio::test]
async fn test_fallback_chain_security_audit_dangerous() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("primary", true)),
    ])
    .unwrap()
    .with_security_auditor(LlmSecurityAuditor::rule_only());

    let err = chain
        .generate("' OR 1=1 --", &empty_schema())
        .await
        .unwrap_err();
    assert!(
        matches!(err, Nl2SqlError::SafetyError(_)),
        "危险输入应被安全审计拦截: {:?}",
        err
    );
}

#[tokio::test]
async fn test_fallback_chain_security_audit_safe_input_passes() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("primary", true)),
    ])
    .unwrap()
    .with_security_auditor(LlmSecurityAuditor::rule_only());

    let result = chain.generate("show all users", &empty_schema()).await.unwrap();
    assert!(result.sql.contains("primary"), "安全输入应通过审计");
}

#[tokio::test]
async fn test_fallback_chain_empty_engines_error() {
    let result = Nl2SqlFallbackChain::new(vec![]);
    assert!(
        matches!(result, Err(Nl2SqlError::ConfigError(_))),
        "空引擎列表应返回 ConfigError"
    );
}

#[tokio::test]
async fn test_fallback_chain_max_depth_error() {
    let engines: Vec<Box<dyn Nl2SqlEngine>> = (0..6)
        .map(|_| Box::new(MockEngine::new("engine", true)) as Box<dyn Nl2SqlEngine>)
        .collect();

    let result = Nl2SqlFallbackChain::new(engines);
    assert!(
        matches!(result, Err(Nl2SqlError::ConfigError(_))),
        "超过 5 个引擎应返回 ConfigError"
    );
}

#[tokio::test]
async fn test_fallback_chain_fallback_log_records_failures() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("engine0", false)),
        Box::new(MockEngine::new("engine1", false)),
        Box::new(MockEngine::new("engine2", true)),
    ])
    .unwrap();

    chain.generate("test query", &empty_schema()).await.unwrap();

    let log = chain.fallback_log();
    assert_eq!(log.len(), 2, "应记录 2 次失败");
    assert!(log[0].contains("engine0"), "第一条日志应记录 engine0 失败");
    assert!(log[1].contains("engine1"), "第二条日志应记录 engine1 失败");
}

#[tokio::test]
async fn test_fallback_chain_validate_delegates_to_first() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("primary", true)),
        Box::new(MockEngine::new("backup", false)),
    ])
    .unwrap();

    let query = SqlQuery {
        sql: "SELECT 1".into(),
        explanation: "test".into(),
        confidence: 1.0,
        dialect: None,
        cache_hit: false,
    };

    let result = chain.validate(&query).await.unwrap();
    assert!(result, "validate 应委托给第一个引擎（should_succeed=true）");
}

#[tokio::test]
async fn test_fallback_chain_three_engines_second_succeeds() {
    let chain = Nl2SqlFallbackChain::new(vec![
        Box::new(MockEngine::new("gpt4", false)),
        Box::new(MockEngine::new("gpt35", true)),
        Box::new(MockEngine::new("local", true)),
    ])
    .unwrap();

    let result = chain.generate("count orders", &empty_schema()).await.unwrap();
    assert!(result.sql.contains("gpt35"), "应使用第二个引擎");

    let log = chain.fallback_log();
    assert_eq!(log.len(), 1, "应记录 1 次 fallback");
    assert!(log[0].contains("gpt4"), "日志应记录 gpt4 失败");
}